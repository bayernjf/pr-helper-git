// Tiny i18n layer: UI copy lives in English in the components and is looked up
// here by that English string. Missing keys fall back to the English source, so
// a typo degrades to English instead of showing a raw key.
import { useSyncExternalStore } from 'react';
import { getPref, setPref } from './lib/prefs';

export type Locale = 'en' | 'zh';

const PREF_KEY = 'locale';
const listeners = new Set<() => void>();
let locale: Locale = getPref<Locale>(PREF_KEY, 'en');

export function getLocale(): Locale {
  return locale;
}

export function setLocale(next: Locale): void {
  if (next !== 'en' && next !== 'zh') return;
  if (next === locale) return;
  locale = next;
  setPref(PREF_KEY, next);
  for (const listener of listeners) listener();
}

export function subscribeLocale(listener: () => void): () => void {
  listeners.add(listener);
  return () => listeners.delete(listener);
}

/** Re-render the tree when the locale changes. */
export function useLocale(): Locale {
  return useSyncExternalStore(subscribeLocale, getLocale, getLocale);
}

