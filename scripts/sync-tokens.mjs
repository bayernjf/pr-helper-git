// Generate src/design/tokens.css for BOTH repos from design/tokens.json.
// The two repos must never drift: this single file is the design-token source,
// run `node scripts/sync-tokens.mjs` after editing it.
//
// pr-helper-git styles.css keeps its legacy variable names (--bg, --panel, …)
// in a static alias block referencing these shared vars, so theme flips
// cascade automatically.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.dirname(HERE);
const TOKENS = JSON.parse(fs.readFileSync(path.join(ROOT, 'design', 'tokens.json'), 'utf8'));
// pr-helper-git archived 2026-11-10 — git2 is now the sole target.
const TARGETS = [ROOT];

const block = (colors) =>
  Object.entries(colors)
    .map(([k, v]) => `  --${k}: ${v};`)
    .join('\n');

const fontBlock = (font) =>
  Object.entries(font)
    .map(([k, v]) => `  --fs-${k}: ${v};`)
    .join('\n');

const radiusBlock = (radius) =>
  Object.entries(radius)
    .map(([k, v]) => `  --radius-${k}: ${v};`)
    .join('\n');

const css = `/* GENERATED by scripts/sync-tokens.mjs — DO NOT EDIT.
   Source of truth: design/tokens.json (shared by pr-helper-git). */

:root {
${block(TOKENS.color)}

${fontBlock(TOKENS['font-size'])}

${radiusBlock(TOKENS.radius)}

  --shadow-sm: ${TOKENS['shadow-dark'].sm};
  --shadow-lg: ${TOKENS['shadow-dark'].lg};
}

html[data-theme='light'] {
${block(TOKENS['color-light'])}

  --shadow-sm: ${TOKENS['shadow-light'].sm};
  --shadow-lg: ${TOKENS['shadow-light'].lg};
}
`;

// Accent presets: one selector block per accent (dark overrides, then the
// light-theme variant). The default violet owns no selector — tokens.css
// already carries its values on :root / html[data-theme='light'].
const accentsCss = ['/* GENERATED by scripts/sync-tokens.mjs — DO NOT EDIT.',
  '   Accent presets from design/tokens.json; violet is the default and lives',
  '   in tokens.css, so only the non-default accents get selector blocks. */', ''];
for (const [name, preset] of Object.entries(TOKENS.accents)) {
  if (name === 'violet') continue;
  accentsCss.push(`html[data-accent='${name}'] {`);
  accentsCss.push(block(preset.dark));
  accentsCss.push('}');
  accentsCss.push('');
  accentsCss.push(`html[data-theme='light'][data-accent='${name}'] {`);
  accentsCss.push(block(preset.light));
  accentsCss.push('}');
  accentsCss.push('');
}
accentsCss.push('');

// Swatch single source for the settings panel: per accent, the accent hex and
// the resolved on-accent text color for each theme.
const swatch = Object.entries(TOKENS.accents)
  .map(([name, preset]) => {
    const onDark = preset.dark['on-accent'] ?? TOKENS.color['on-accent'];
    const onLight = preset.light['on-accent'] ?? TOKENS['color-light']['on-accent'];
    return `  ${name}: { dark: '${preset.dark.accent}', light: '${preset.light.accent}', onDark: '${onDark}', onLight: '${onLight}' },`;
  })
  .join('\n');
const accentsTs = `// GENERATED by scripts/sync-tokens.mjs — DO NOT EDIT.
// Accent swatches for the settings panel, sourced from design/tokens.json so
// the picker can never drift from accents.css.
import type { Accent } from '../lib/appearance';

export const ACCENT_SWATCH: Record<Accent, { dark: string; light: string; onDark: string; onLight: string }> = {
${swatch}
};
`;

let written = 0;
for (const target of TARGETS) {
  const dir = path.join(target, 'src', 'design');
  fs.mkdirSync(dir, { recursive: true });
  fs.writeFileSync(path.join(dir, 'tokens.css'), css);
  fs.writeFileSync(path.join(dir, 'accents.css'), accentsCss.join('\n'));
  fs.writeFileSync(path.join(dir, 'accents.ts'), accentsTs);
  // Keep a copy of the source JSON next to the CSS for traceability.
  fs.writeFileSync(path.join(dir, 'tokens.source.json'), JSON.stringify(TOKENS, null, 2) + '\n');
  written++;
}
console.log(`tokens.css + accents.css + accents.ts written to ${written} repos`);
