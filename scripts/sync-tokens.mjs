// Generate src/design/tokens.css for BOTH repos from design/tokens.json.
// The two repos must never drift: this single file is the design-token source,
// run `node scripts/sync-tokens.mjs` after editing it.
//
// pr-helper-git2 styles.css keeps its legacy variable names (--bg, --panel, …)
// in a static alias block referencing these shared vars, so theme flips
// cascade automatically.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.dirname(HERE);
const TOKENS = JSON.parse(fs.readFileSync(path.join(ROOT, 'design', 'tokens.json'), 'utf8'));
// pr-helper-git archived 2026-11-10 — git2 is now the sole target.
const TARGETS = [ROOT];

const block = (colors) =>
  Object.entries(colors)
    .map(([k, v]) => `  --${k}: ${v};`)
    .join('\n');

const fontBlock = (font) =>
  Object.entries(font)
    .map(([k, v]) => `  --fs-${k}: ${v};`)
    .join('\n');

const spaceBlock = (space) =>
  Object.entries(space)
    .map(([k, v]) => `  --sp-${k}: ${v};`)
    .join('\n');

const radiusBlock = (radius) =>
  Object.entries(radius)
    .map(([k, v]) => `  --radius-${k}: ${v};`)
    .join('\n');

const css = `/* GENERATED by scripts/sync-tokens.mjs — DO NOT EDIT.
   Source of truth: design/tokens.json (shared by pr-helper-git and pr-helper-git2). */

:root {
${block(TOKENS.color)}

${fontBlock(TOKENS['font-size'])}

${spaceBlock(TOKENS.space)}

${radiusBlock(TOKENS.radius)}

  --shadow-sm: ${TOKENS['shadow-dark'].sm};
  --shadow-lg: ${TOKENS['shadow-dark'].lg};
}

html[data-theme='light'] {
${block(TOKENS['color-light'])}

  --shadow-sm: ${TOKENS['shadow-light'].sm};
  --shadow-lg: ${TOKENS['shadow-light'].lg};
}
`;

let written = 0;
for (const target of TARGETS) {
  const dir = path.join(target, 'src', 'design');
  fs.mkdirSync(dir, { recursive: true });
  fs.writeFileSync(path.join(dir, 'tokens.css'), css);
  // Keep a copy of the source JSON next to the CSS for traceability.
  fs.writeFileSync(path.join(dir, 'tokens.source.json'), JSON.stringify(TOKENS, null, 2) + '\n');
  written++;
}
console.log(`tokens.css written to ${written} repos`);
